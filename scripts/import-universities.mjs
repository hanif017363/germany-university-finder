// Imports the CC0-licensed 2024 dataset (about 400 records) into data/imported-universities.js.
// The source dataset is not the official 2025/26 register and should be checked before production.
import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/jacksonbarreto/Higher-Education-Institutions-in-Germany-Dataset-2025/main/de-2024-heis.csv";

const states = {
  DE1: "Baden-Württemberg",
  DE2: "Bavaria",
  DE3: "Berlin",
  DE4: "Brandenburg",
  DE5: "Bremen",
  DE6: "Hamburg",
  DE7: "Hesse",
  DE8: "Mecklenburg-Vorpommern",
  DE9: "Lower Saxony",
  DEA: "North Rhine-Westphalia",
  DEB: "Rhineland-Palatinate",
  DEC: "Saarland",
  DED: "Saxony",
  DEE: "Saxony-Anhalt",
  DEF: "Schleswig-Holstein",
  DEG: "Thuringia",
};

function parseCSV(text) {
  const rows = [];
  let row = [], cell = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n") {
      row.push(cell.replace(/\r$/, ""));
      if (row.some((v) => v.trim() !== "")) rows.push(row);
      row = []; cell = "";
    } else cell += ch;
  }
  if (cell.length || row.length) {
    row.push(cell.replace(/\r$/, ""));
    rows.push(row);
  }
  const headers = rows.shift().map((h) => h.trim());
  return rows.map((values) =>
    Object.fromEntries(headers.map((header, i) => [header, (values[i] ?? "").trim()]))
  );
}

function normalizeUrl(value) {
  if (!value) return "";
  return /^https?:\/\//i.test(value) ? value : `https://${value}`;
}

function cleanLocation(value) {
  return (value || "")
    .replace(/,\s*(Kreisfreie Stadt|Stadtkreis|Landkreis|Landkreis|Kreis)$/i, "")
    .replace(/\s*\(.*\)$/, "")
    .trim();
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Could not download dataset: HTTP ${response.status}. Check your internet connection and try again.`);
}

const rows = parseCSV(await response.text());
const imported = rows
  .map((row) => {
    const code = row.NUTS2 || "";
    const stateKey = code.slice(0, 3);
    const name = row.Name;
    const state = states[stateKey];
    const city =
      cleanLocation(row.NUTS3_Label_2021) ||
      cleanLocation(row.NUTS3_Label_2016) ||
      row.NUTS2_Label_2021 ||
      row.NUTS2_Label_2016 ||
      "";
    const type = String(row.Category).toLowerCase() === "private" ? "private" : "public";
    const url = normalizeUrl(row.Url);
    if (!name || !state) return null;
    return { name, city, state, type, url, institutionType: row.Institution_Category_Standardized || "Other" };
  })
  .filter(Boolean);

const unique = new Map();
for (const uni of imported) {
  const key = uni.name.trim().toLocaleLowerCase("de");
  if (!unique.has(key)) unique.set(key, uni);
}

const sourceNote = `// Generated by scripts/import-universities.mjs from the CC0-licensed Higher Education Institutions in Germany Dataset 2025.\n// Source snapshot: dataset collected in December 2024; it is not a guaranteed current official register.\n// ${unique.size} unique source records. City may reflect a district/region label where the source does not provide a city.\n\n`;
const output = sourceNote + `export const imported = ${JSON.stringify([...unique.values()], null, 2)};\n`;
await writeFile(new URL("../data/imported-universities.js", import.meta.url), output, "utf8");
console.log(`Imported ${unique.size} unique institutions into data/imported-universities.js.`);
